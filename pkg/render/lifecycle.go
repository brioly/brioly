package render

import (
	"fmt"
	"strings"

	"github.com/brioly/brioly/pkg/facts"
	"github.com/brioly/brioly/pkg/lifecycle"
)

// Lifecycle renders the version support document: when the versions the
// system runs on stop being supported. g holds the escaped copy of the
// snapshot, for names and sources; raw is the snapshot as collected, which
// versions are read from.
//
// data is the table of dates; nil means it could not be loaded, and the
// document says so.
//
// How close an end of support is, is judged against the time of the scan,
// which is not printed: the document changes when a version changes, when a
// date is crossed, or when the table of dates changes, and not otherwise.
func Lifecycle(g *graph, raw *facts.Snapshot, data *lifecycle.Table) string {
	var b strings.Builder
	b.WriteString("# Version support\n\n")
	if data == nil {
		b.WriteString("> The table of end-of-support dates could not be loaded, so this document could not be made. The other documents do not depend on it.\n")
		return b.String()
	}
	fmt.Fprintf(&b, "> Generated by brioly from collected facts and a table of end-of-support dates (from [endoflife.date](%s), as of %s). "+
		"No AI model is involved: a version that is not in the table is listed as not known, never guessed. "+
		"\"Ends soon\" means within six months of the scan.\n\n", data.Source, data.Updated)
	writeCoverageWarnings(&b, g.snap)

	items := lifecycle.Find(raw, raw.FinishedAt, data)
	if len(items) == 0 {
		b.WriteString("Nothing with a version that brioly tracks was found: no clusters, databases, function runtimes, base images or tracked frameworks.\n")
		return b.String()
	}
	var attention, fine, unknown []lifecycle.Item
	for _, it := range items {
		switch it.State {
		case lifecycle.Ended, lifecycle.EndsSoon:
			attention = append(attention, it)
		case lifecycle.Supported:
			fine = append(fine, it)
		default:
			unknown = append(unknown, it)
		}
	}
	name := func(it lifecycle.Item) (string, string) {
		f := g.byID[it.FactID]
		return mdEscape(displayName(f)), evidence(f)
	}
	dated := func(title, lead string, list []lifecycle.Item) {
		if len(list) == 0 {
			return
		}
		b.WriteString("## " + title + "\n\n" + lead + "\n\n| What | Name | Version | Standard support ends | Status | Source |\n|---|---|---|---|---|---|\n")
		for _, it := range list {
			n, src := name(it)
			ends := it.EOL
			if ends == "ended" {
				ends = "ended (date not given)"
			}
			status := map[string]string{lifecycle.Ended: "**Ended**", lifecycle.EndsSoon: "**Ends soon**", lifecycle.Supported: "Supported"}[it.State]
			if it.Extended != "" {
				status += "; extended support until " + it.Extended
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", it.What, n, code(Escape(it.Version)), ends, status, src)
		}
		b.WriteString("\n")
	}
	dated("Needs attention", "Standard support for these has ended or ends soon. After that, fixes stop or (for managed services) an upgrade is forced or extended support is charged.", attention)
	dated("Supported", "These are in standard support, soonest end first.", fine)
	if len(unknown) > 0 {
		b.WriteString("## No end date known\n\n| What | Name | Version | Why | Source |\n|---|---|---|---|---|\n")
		for _, it := range unknown {
			n, src := name(it)
			why := "no end of support is announced for this version"
			switch {
			case it.State == lifecycle.Unknown && it.Product == "":
				why = "brioly has no dates for this product"
			case it.State == lifecycle.Unknown:
				why = "this version is not in the table for " + it.Product
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", it.What, n, code(Escape(it.Version)), why, src)
		}
		b.WriteString("\n")
	}
	b.WriteString("## Not covered\n\n" +
		"- Versions brioly does not collect: operating systems of EC2 instances and nodes, language versions that are not visible in a base image, and libraries other than a few frameworks.\n" +
		"- A base image without a version in its tag (`node:latest`, a digest only) and images that are not official images.\n" +
		"- Whether a supported version has the latest patches.\n")
	return b.String()
}
