// Package render turns a finalized snapshot into documents. Everything here
// is deterministic: the same snapshot always renders the same bytes, so an
// unchanged environment never produces a document diff.
package render

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/brioly/brioly/pkg/facts"
)

// Files are the document paths written by Write, relative to the output
// directory.
const (
	ArchitectureFile = "architecture.md"
	TechStackFile    = "tech-stack.md"
	DiagramFile      = "diagrams/system.mmd"
	FactsFile        = "facts.json"
)

// Files renders the deterministic documents of a snapshot in memory, keyed
// by their path relative to the output directory. Callers that do not write
// to a directory (brioly Cloud serves documents from stored snapshots) use
// this; Write is Files plus the file system.
func Files(s *facts.Snapshot) (map[string][]byte, error) {
	// Documents are written from a copy whose values are escaped; the
	// diagram escapes its own labels and facts.json is the snapshot as it is.
	text, err := escaped(s)
	if err != nil {
		return nil, err
	}
	g := newGraph(text)
	diagram := Diagram(newGraph(s))
	files := map[string][]byte{
		ArchitectureFile: []byte(Architecture(g, diagram)),
		TechStackFile:    []byte(TechStack(g)),
		DiagramFile:      []byte(diagram),
	}
	raw, err := json.MarshalIndent(s, "", "  ")
	if err != nil {
		return nil, err
	}
	files[FactsFile] = append(raw, '\n')
	return files, nil
}

// Write renders the deterministic documents of a snapshot into dir.
func Write(dir string, s *facts.Snapshot) error {
	files, err := Files(s)
	if err != nil {
		return err
	}
	for rel, body := range files {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, body, 0o644); err != nil {
			return err
		}
	}
	return nil
}

const generatedNote = "> Generated by brioly from collected facts. Every statement links to its source. This file is regenerated on every run: put what you know (names, notes) in the components file instead of editing here.\n"

// Architecture renders architecture.md.
func Architecture(g *graph, diagram string) string {
	var b strings.Builder
	b.WriteString("# Architecture\n\n" + generatedNote + "\n")
	writeCoverageWarnings(&b, g.snap)

	if diagram != "" {
		b.WriteString("## System diagram\n\n```mermaid\n" + diagram + "```\n\n")
	}

	if comps := g.snap.Components; len(comps) > 0 {
		b.WriteString("## Components\n\n")
		// One table per place the components run, when there is more than
		// one such place: a system that is all on one platform keeps the
		// single table it always had.
		groups := map[string][]facts.Component{}
		for _, c := range sortedComponents(comps) {
			p := platform(g.byID[c.Anchor])
			groups[p] = append(groups[p], c)
		}
		for _, p := range platforms {
			list := groups[p]
			if len(list) == 0 {
				continue
			}
			if len(groups) > 1 {
				fmt.Fprintf(&b, "### %s\n\n", p)
			}
			b.WriteString("| Component | Role | Made of |\n|---|---|---|\n")
			for _, c := range list {
				var members []string
				for _, m := range c.Members {
					if f, ok := g.byID[m]; ok && f.ID != c.Anchor {
						members = append(members, displayName(f))
					}
				}
				fmt.Fprintf(&b, "| %s | %s | %s — %s |\n", mdEscape(c.Name), c.Role,
					mdEscape(strings.Join(append([]string{displayName(g.byID[c.Anchor])}, members...), ", ")), evidence(g.byID[c.Anchor]))
			}
			b.WriteString("\n")
		}
		writeNotes(&b, g.snap)
	}

	if vpcs := g.kind("aws.ec2.vpc"); len(vpcs) > 0 {
		b.WriteString("## Network\n\n")
		for _, v := range vpcs {
			fmt.Fprintf(&b, "### VPC %s\n\n", displayName(v))
			fmt.Fprintf(&b, "- CIDR: %s — %s\n", strings.Join(listAttr(v, "cidr_blocks"), ", "), evidence(v))
			for _, gw := range g.sources(v.ID, facts.EdgeAttachedTo) {
				if gw.Kind == "aws.ec2.internet_gateway" {
					fmt.Fprintf(&b, "- Internet gateway: %s — %s\n", displayName(gw), evidence(gw))
				}
			}
			var subnets []facts.Fact
			for _, c := range g.targets(v.ID, facts.EdgeContains) {
				if c.Kind == "aws.ec2.subnet" {
					subnets = append(subnets, c)
				}
			}
			if len(subnets) > 0 {
				b.WriteString("\n| Subnet | CIDR | AZ | Exposure | NAT gateway | Source |\n|---|---|---|---|---|---|\n")
				for _, sn := range subnets {
					exposure := "private"
					if v, ok := sn.Attributes["public"]; !ok {
						exposure = "unknown"
					} else if v == true {
						exposure = "public"
					}
					var nats []string
					for _, n := range g.targets(sn.ID, facts.EdgeContains) {
						if n.Kind == "aws.ec2.nat_gateway" {
							nats = append(nats, displayName(n))
						}
					}
					fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", mdEscape(displayName(sn)), strAttr(sn, "cidr_block"),
						strAttr(sn, "availability_zone"), exposure, strings.Join(nats, ", "), evidence(sn))
				}
			}
			b.WriteString("\n")
		}
	}

	// Ingresses no load balancer fact serves are entry points of their own.
	var ingresses []facts.Fact
	for _, in := range g.kind("k8s.ingress") {
		served := false
		for _, src := range g.sources(in.ID, facts.EdgeRoutesTo) {
			served = served || src.Kind == "aws.elbv2.load_balancer"
		}
		if !served {
			ingresses = append(ingresses, in)
		}
	}
	if lbs := g.kind("aws.elbv2.load_balancer"); len(lbs)+len(ingresses) > 0 {
		b.WriteString("## Entry points\n\n")
		for _, in := range ingresses {
			fmt.Fprintf(&b, "### %s (Kubernetes Ingress)\n\n", displayName(in))
			writeIngress(&b, g, in, "- ")
			b.WriteString("- No load balancer in the scanned account reports this Ingress: it is served inside the cluster or from outside the scan.\n\n")
		}
		for _, lb := range lbs {
			fmt.Fprintf(&b, "### %s (%s, %s)\n\n- Source: %s\n", displayName(lb), strAttr(lb, "type"), strAttr(lb, "scheme"), evidence(lb))
			writeKubernetesOwner(&b, g, lb)
			for _, l := range g.targets(lb.ID, facts.EdgeContains) {
				fmt.Fprintf(&b, "- Listener %s:%s, default action %s\n", strAttr(l, "protocol"), strAttr(l, "port"), code(strAttr(l, "default_action")))
				for _, tg := range g.targets(l.ID, facts.EdgeRoutesTo) {
					writeTargetGroup(&b, g, tg, "  - default → ")
				}
				for _, r := range byPriority(g.targets(l.ID, facts.EdgeContains)) {
					fmt.Fprintf(&b, "  - Rule %s when %s\n", strAttr(r, "priority"), code(strings.Join(listAttr(r, "conditions"), " AND ")))
					for _, tg := range g.targets(r.ID, facts.EdgeRoutesTo) {
						writeTargetGroup(&b, g, tg, "    - → ")
					}
				}
			}
			b.WriteString("\n")
		}
	}

	writeCompute(&b, g)
	writeData(&b, g)
	writeDependencies(&b, g)
	writeExposure(&b, g)
	return b.String()
}

func writeTargetGroup(b *strings.Builder, g *graph, tg facts.Fact, prefix string) {
	var names []string
	for _, w := range g.targets(tg.ID, facts.EdgeRoutesTo) {
		name := displayName(w)
		if c, ok := g.clusterOf(w.ID); ok {
			name = fmt.Sprintf("nodes of EKS cluster %s (node group %s)", displayName(c), strAttr(w, "eks_nodegroup"))
		}
		names = append(names, name)
	}
	target := "no target found"
	if incomplete(g.snap, tg) {
		// Registered targets could not be read: do not say there are none.
		target = "targets were not read"
	}
	if len(names) > 0 {
		target = strings.Join(names, ", ")
		if incomplete(g.snap, tg) {
			target += " (as last read; targets were not read in this scan)"
		}
	}
	health := ""
	if p := strAttr(tg, "health_check_path"); p != "" {
		health = ", health check " + code(p)
	} else if p := strAttr(tg, "health_check_protocol"); p != "" {
		health = ", " + p + " health check"
	}
	fmt.Fprintf(b, "%starget group %s (%s:%s%s) → %s — %s\n", prefix, displayName(tg),
		strAttr(tg, "protocol"), strAttr(tg, "port"), health, target, evidence(tg))
}

// writeKubernetesOwner says which Kubernetes object created a load balancer
// (from its tags) and, when a repository declares that object, where.
func writeKubernetesOwner(b *strings.Builder, g *graph, lb facts.Fact) {
	cluster := strAttr(lb, "k8s_cluster")
	in := ""
	if cluster != "" {
		in = " in cluster " + code(cluster)
	}
	if v := strAttr(lb, "k8s_service"); v != "" {
		fmt.Fprintf(b, "- Created by Kubernetes for Service %s%s (AWS name: %s)\n", code(v), in, code(strAttr(lb, "lb_name")))
	}
	if v := strAttr(lb, "k8s_ingress"); v != "" {
		fmt.Fprintf(b, "- Created by Kubernetes for Ingress %s%s (AWS name: %s)\n", code(v), in, code(strAttr(lb, "lb_name")))
	}
	for _, in := range g.targets(lb.ID, facts.EdgeRoutesTo) {
		if in.Kind == "k8s.ingress" {
			writeIngress(b, g, in, "- Serves ")
		}
	}
	services, _ := g.manifestsBehind(lb.ID)
	for _, svc := range services {
		var names []string
		for _, w := range g.targets(svc.ID, facts.EdgeRoutesTo) {
			if w.Kind == "k8s.workload" {
				names = append(names, fmt.Sprintf("%s %s (%s)", strAttr(w, "workload_kind"), code(displayName(w)), evidence(w)))
			}
		}
		ports := ""
		if pm := strings.Join(listAttr(svc, "port_mappings"), ", "); pm != "" {
			ports = " (port → container port: " + pm + ")"
		}
		if live(svc) {
			// Read from the cluster: the Service reports this load balancer
			// and its selector was matched against the running workloads.
			fmt.Fprintf(b, "- Kubernetes Service %s%s selects %s — %s\n", code(strAttr(svc, "namespace")+"/"+displayName(svc)), ports, orNone(names), evidence(svc))
			continue
		}
		fmt.Fprintf(b, "- Inferred: that Service is declared in %s%s and selects %s\n", evidence(svc), ports, orNone(names))
	}
}

// writeIngress describes an Ingress read from a cluster.
func writeIngress(b *strings.Builder, g *graph, in facts.Fact, prefix string) {
	class := ""
	if c := strAttr(in, "ingress_class"); c != "" {
		class = ", class " + code(c)
	}
	tls := ""
	if boolAttr(in, "tls") {
		tls = ", TLS"
	}
	fmt.Fprintf(b, "%sKubernetes Ingress %s%s%s — %s\n", prefix, code(strAttr(in, "namespace")+"/"+displayName(in)), class, tls, evidence(in))
	for _, r := range listAttr(in, "routes") {
		fmt.Fprintf(b, "  - %s\n", code(r))
	}
}

// writeClusterWorkloads lists what runs in each cluster, as read from its
// API server, or says that the cluster was not read.
func writeClusterWorkloads(b *strings.Builder, g *graph, clusters []facts.Fact) {
	for _, c := range clusters {
		var ws []facts.Fact
		for _, w := range g.sources(c.ID, facts.EdgeRunsOn) {
			if w.Kind == "k8s.workload" && live(w) {
				ws = append(ws, w)
			}
		}
		if len(ws) == 0 {
			tried := false
			for _, cov := range g.snap.Coverage {
				tried = tried || cov.Connector == liveConnector && cov.Kind == "k8s.workload" && cov.Scope == c.Name && cov.Status != facts.CoverageComplete
			}
			switch {
			case tried:
				fmt.Fprintf(b, "The Kubernetes API of **%s** could not be read in this scan (see \"Incomplete scan\" at the top): what runs in it is known only from manifests in the scanned repositories.\n\n", displayName(c))
			case clusterRead(g, c):
				fmt.Fprintf(b, "No workloads run in **%s** outside the system namespaces.\n\n", displayName(c))
			default:
				fmt.Fprintf(b, "The Kubernetes API of **%s** was not read: what runs in it is known only from manifests in the scanned repositories. Enable `sources.kubernetes` to read it.\n\n", displayName(c))
			}
			continue
		}
		sort.SliceStable(ws, func(i, j int) bool {
			a, c := strAttr(ws[i], "namespace")+"/"+ws[i].Name, strAttr(ws[j], "namespace")+"/"+ws[j].Name
			return a < c
		})
		fmt.Fprintf(b, "Workloads in **%s**, read from its API server:\n\n| Workload | Kind | Namespace | Images | Ports | Replicas | Reached through | Declared in |\n|---|---|---|---|---|---|---|---|\n", displayName(c))
		for _, w := range ws {
			var via, decl []string
			for _, svc := range g.sources(w.ID, facts.EdgeRoutesTo) {
				if svc.Kind == "k8s.service" && live(svc) {
					via = append(via, fmt.Sprintf("Service %s (%s, %s)", displayName(svc), strAttr(svc, "service_type"), strings.Join(listAttr(svc, "port_mappings"), ", ")))
				}
			}
			for _, m := range g.sources(w.ID, facts.EdgeDefines) {
				decl = append(decl, evidence(m))
			}
			kind := strAttr(w, "workload_kind")
			if s := strAttr(w, "schedule"); s != "" {
				kind += " " + code(s)
			}
			fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s | %s | %s |\n", mdEscape(displayName(w)), mdEscape(kind), strAttr(w, "namespace"),
				mdEscape(strings.Join(listAttr(w, "image_repositories"), ", ")), strings.Trim(strings.Join(strings.Fields(strAttr(w, "ports")), ", "), "[]"),
				strAttr(w, "replicas"), mdEscape(strings.Join(via, "; ")), strings.Join(decl, ", "))
		}
		b.WriteString("\nSystem namespaces (`kube-system`, ...) are left out. \"Declared in\" is inferred from the kind, namespace and name of a manifest.\n\n")
	}
}

// clusterRead reports whether the scan read this cluster's API server in
// full.
func clusterRead(g *graph, c facts.Fact) bool {
	for _, cov := range g.snap.Coverage {
		if cov.Connector == liveConnector && cov.Kind == "k8s.workload" && cov.Scope == c.Name {
			return cov.Status == facts.CoverageComplete
		}
	}
	return false
}

func writeCompute(b *strings.Builder, g *graph) {
	services, fns := g.kind("aws.ecs.service"), g.kind("aws.lambda.function")
	instances, clusters, kclusters := g.kind("aws.ec2.instance"), g.kind("aws.eks.cluster"), g.kind("k8s.cluster")
	var asgs []facts.Fact
	for _, a := range g.kind("aws.autoscaling.group") {
		if _, ok := g.clusterOf(a.ID); !ok {
			asgs = append(asgs, a) // node groups are listed with their cluster
		}
	}
	if len(services)+len(fns)+len(asgs)+len(instances)+len(clusters)+len(kclusters) == 0 {
		return
	}
	b.WriteString("## Compute\n\n")
	if len(clusters) > 0 {
		b.WriteString("### EKS clusters\n\n")
		for _, c := range clusters {
			access := "private"
			if boolAttr(c, "endpoint_public_access") {
				access = "public from " + strings.Join(listAttr(c, "public_access_cidrs"), ", ")
				if boolAttr(c, "endpoint_private_access") {
					access += " and private"
				}
			}
			fmt.Fprintf(b, "- Cluster **%s**: Kubernetes %s, API endpoint %s — %s\n", displayName(c), strAttr(c, "version"), access, evidence(c))
			for _, ng := range g.targets(c.ID, facts.EdgeContains) {
				if ng.Kind != "aws.eks.nodegroup" {
					continue
				}
				fmt.Fprintf(b, "  - Node group **%s**: %s–%s × %s (%s, %s) — %s\n", displayName(ng), strAttr(ng, "min_size"), strAttr(ng, "max_size"),
					strings.Join(listAttr(ng, "instance_types"), "/"), strAttr(ng, "capacity_type"), strAttr(ng, "ami_type"), evidence(ng))
			}
		}
		b.WriteString("\n")
		writeClusterWorkloads(b, g, clusters)
	}
	if len(kclusters) > 0 {
		b.WriteString("### Kubernetes clusters\n\n")
		for _, c := range kclusters {
			version := "version not read"
			if v := strAttr(c, "version"); v != "" {
				version = "Kubernetes " + v
			}
			fmt.Fprintf(b, "- Cluster **%s**: %s, API server %s — %s\n", displayName(c), version, code(strAttr(c, "server")), evidence(c))
		}
		b.WriteString("\n")
		writeClusterWorkloads(b, g, kclusters)
	}
	if len(services) > 0 {
		b.WriteString("### ECS services\n\n| Service | Cluster | Launch | Containers | Source |\n|---|---|---|---|---|\n")
		for _, s := range services {
			cluster := ""
			for _, c := range g.sources(s.ID, facts.EdgeContains) {
				if c.Kind == "aws.ecs.cluster" {
					cluster = displayName(c)
				}
			}
			var containers []string
			for _, td := range g.targets(s.ID, facts.EdgeUses) {
				for _, c := range containerList(td) {
					containers = append(containers, c)
				}
			}
			fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n", mdEscape(displayName(s)), mdEscape(cluster), strAttr(s, "launch_type"),
				mdEscape(strings.Join(containers, "; ")), evidence(s))
		}
		b.WriteString("\n")
	}
	if len(fns) > 0 {
		b.WriteString("### Lambda functions\n\n| Function | Runtime | Memory (MB) | In VPC | Source |\n|---|---|---|---|---|\n")
		for _, f := range fns {
			inVPC := "no"
			if len(listAttr(f, "subnet_ids")) > 0 {
				inVPC = "yes"
			}
			fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n", mdEscape(displayName(f)), strAttr(f, "runtime"), strAttr(f, "memory_mb"), inVPC, evidence(f))
		}
		b.WriteString("\n")
	}
	if len(asgs)+len(instances) > 0 {
		b.WriteString("### EC2\n\n")
		for _, a := range asgs {
			lt := strAttr(a, "launch_template")
			if lt == "" {
				lt = strAttr(a, "launch_configuration")
			}
			fmt.Fprintf(b, "- Auto Scaling group **%s**: %s–%s instances from %s — %s\n", displayName(a),
				strAttr(a, "min_size"), strAttr(a, "max_size"), code(lt), evidence(a))
		}
		for _, in := range instances {
			fmt.Fprintf(b, "- Instance **%s** (%s) — %s\n", displayName(in), strAttr(in, "instance_type"), evidence(in))
		}
		b.WriteString("\n")
	}
}

func containerList(td facts.Fact) []string {
	cs, _ := td.Attributes["containers"].([]any)
	var out []string
	for _, c := range cs {
		m, ok := c.(map[string]any)
		if !ok {
			continue
		}
		s := fmt.Sprintf("%v (%v)", m["name"], m["image_repository"])
		if ports := fmt.Sprint(m["ports"]); ports != "[]" && ports != "<nil>" {
			s += " ports " + ports
		}
		out = append(out, s)
	}
	return out
}

func writeData(b *strings.Builder, g *graph) {
	clusters, instances := g.kind("aws.rds.cluster"), g.kind("aws.rds.instance")
	if len(clusters)+len(instances) == 0 {
		return
	}
	b.WriteString("## Data stores\n\n| Database | Engine | Multi-AZ | Encrypted | Public | Source |\n|---|---|---|---|---|---|\n")
	for _, d := range clusters {
		fmt.Fprintf(b, "| %s (cluster) | %s %s | %v | %v | %v | %s |\n", mdEscape(displayName(d)), strAttr(d, "engine"), strAttr(d, "engine_version"),
			boolAttr(d, "multi_az"), boolAttr(d, "storage_encrypted"), boolAttr(d, "publicly_accessible"), evidence(d))
	}
	for _, d := range instances {
		if strAttr(d, "cluster_id") != "" {
			continue // described by its cluster
		}
		fmt.Fprintf(b, "| %s | %s %s | %v | %v | %v | %s |\n", mdEscape(displayName(d)), strAttr(d, "engine"), strAttr(d, "engine_version"),
			boolAttr(d, "multi_az"), boolAttr(d, "storage_encrypted"), boolAttr(d, "publicly_accessible"), evidence(d))
	}
	b.WriteString("\n")
}

func writeDependencies(b *strings.Builder, g *graph) {
	var lines []string
	for _, e := range g.snap.Edges {
		if e.Type != facts.EdgeDependsOn {
			continue
		}
		from, ok1 := g.byID[e.From]
		to, ok2 := g.byID[e.To]
		if !ok1 || !ok2 {
			continue
		}
		lines = append(lines, fmt.Sprintf("- **%s** uses **%s** (%s) — found in the configuration of %s", displayName(from), displayName(to), to.Kind, evidence(from)))
	}
	if len(lines) == 0 {
		return
	}
	sort.Strings(lines)
	b.WriteString("## Runtime dependencies\n\n" + strings.Join(lines, "\n") + "\n\n")
}

// writeExposure lists security groups open to the whole internet.
func writeExposure(b *strings.Builder, g *graph) {
	var lines []string
	for _, sg := range g.kind("aws.ec2.security_group") {
		for _, rule := range listAttr(sg, "ingress") {
			if strings.HasSuffix(rule, ":0.0.0.0/0") || strings.HasSuffix(rule, ":::/0") {
				var attached []string
				for _, t := range g.targets(sg.ID, facts.EdgeAttachedTo) {
					attached = append(attached, displayName(t))
				}
				attached = append(attached, listAttr(sg, "other_interfaces")...)
				use := "attached to: " + orNone(attached)
				// Without the list of network interfaces, finding no
				// attachment does not mean there is none.
				if _, known := sg.Details["other_interfaces"]; !known && len(attached) == 0 {
					use = "no attachment found; network interfaces were not read"
				}
				lines = append(lines, fmt.Sprintf("- Security group **%s** allows %s (%s) — %s",
					displayName(sg), code(rule), use, evidence(sg)))
			}
		}
	}
	if len(lines) == 0 {
		return
	}
	b.WriteString("## Internet exposure\n\n" + strings.Join(lines, "\n") + "\n\n")
}

func orNone(ss []string) string {
	if len(ss) == 0 {
		return "nothing"
	}
	return strings.Join(ss, ", ")
}

// incomplete reports whether the scan of f's kind in f's account and region
// did not finish, so that an absence around f proves nothing.
func incomplete(s *facts.Snapshot, f facts.Fact) bool {
	for _, c := range s.Coverage {
		if c.Kind == f.Kind && c.Status != facts.CoverageComplete && c.Connector == f.Source.Connector &&
			c.Scope == f.Source.Scope && c.Region == f.Source.Region {
			return true
		}
	}
	return false
}

func writeCoverageWarnings(b *strings.Builder, s *facts.Snapshot) {
	var lines []string
	for _, c := range s.Coverage {
		if c.Status == facts.CoverageComplete {
			continue
		}
		where := c.Scope
		if c.Region != "" {
			where += "/" + c.Region
		}
		lines = append(lines, fmt.Sprintf("- %s in %s: **%s**", code(c.Kind), where, c.Status))
	}
	if len(lines) == 0 {
		return
	}
	b.WriteString("> **Incomplete scan.** These parts could not be read. What an earlier scan saw of them is kept and marked \"not read\" or \"partly read in this scan\"; anything new in them is missing:\n>\n")
	for _, l := range lines {
		b.WriteString(">" + l[1:] + "\n")
	}
	b.WriteString("\n")
}

// byPriority orders listener rules by their numeric priority, the order in
// which the load balancer evaluates them.
func byPriority(rules []facts.Fact) []facts.Fact {
	out := append([]facts.Fact(nil), rules...)
	prio := func(f facts.Fact) int {
		n, err := strconv.Atoi(strAttr(f, "priority"))
		if err != nil {
			return 1 << 30
		}
		return n
	}
	sort.SliceStable(out, func(i, j int) bool { return prio(out[i]) < prio(out[j]) })
	return out
}

// platforms are the places a component can run, in the order their tables
// are written.
var platforms = []string{"AWS", "Kubernetes", "Code"}

// platform says where a component runs, from the resource that stands for
// it. A component whose resource is in AWS may still have members read
// from a cluster or a repository: it is listed once, under its own.
func platform(anchor facts.Fact) string {
	switch {
	case strings.HasPrefix(anchor.Kind, "k8s."):
		return "Kubernetes"
	case strings.HasPrefix(anchor.Kind, "code."):
		return "Code"
	default:
		return "AWS"
	}
}

func sortedComponents(comps []facts.Component) []facts.Component {
	out := append([]facts.Component(nil), comps...)
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].Role != out[j].Role {
			return out[i].Role < out[j].Role
		}
		return out[i].Name < out[j].Name
	})
	return out
}

// writeNotes lists the notes people wrote about components, apart from the
// generated text.
func writeNotes(b *strings.Builder, s *facts.Snapshot) {
	if len(s.Annotations) == 0 {
		return
	}
	names := map[string]string{}
	for _, c := range s.Components {
		names[c.ID] = c.Name
	}
	var lines []string
	for _, a := range s.Annotations {
		target := names[a.Target]
		if target == "" {
			// The component this note was written about was not found in
			// this scan. Keep showing the note: it is someone's knowledge.
			target = a.TargetName
			if target == "" {
				target = Escape(a.Target)
			}
			target += " (no longer found)"
		}
		line := fmt.Sprintf("- **%s**: %s", target, strings.ReplaceAll(a.Body, "\n", " "))
		if a.Author != "" {
			line += " — " + a.Author
		}
		lines = append(lines, line)
	}
	sort.Strings(lines)
	b.WriteString("### Notes from the team\n\n" + strings.Join(lines, "\n") + "\n\n")
}
